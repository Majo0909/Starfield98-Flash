'use strict';
const assert=require('node:assert/strict'), fs=require('node:fs'), path=require('node:path');
const window={StarfieldDepth:require('./depth.js')};
new Function('window',fs.readFileSync(path.join(__dirname,'gases.js'),'utf8'))(window);
const gas=Object.create(window.GasClouds.prototype);
gas.layer={}; gas.textures=[{}];
let calls=[];
gas.context={clearRect(){},save(){},restore(){},translate(){},rotate(){},fillRect(){},drawImage(){calls.push(this.globalAlpha);}};
const cloud={x:0,y:0,z:190,radius:16,stretch:1.3,shape:0,angle:0,color:0,texture:0,density:1};
gas.clouds=[cloud];
gas.render({drawImage(){}},1280,720,0,0,0,1);
assert(calls.some(a=>a>0),'giant near edge remains visible beyond center far plane');
console.log('PASS radius-aware giant far fade');
gas.render({drawImage(){}},300,3000,0,0,0,1);
assert(Math.max(gas.layer.width,gas.layer.height)<=960,'portrait and landscape compositing are bounded in BOTH axes');
console.log('PASS portrait layer bounded');
cloud.x=10000; calls=[];
gas.render({drawImage(){}},1280,720,0,0,0,1);
assert.equal(calls.length,0,'offscreen cloud culled before drawing');
console.log('PASS offscreen sprite culling');
cloud.x=0; cloud.z=-13; gas.distance=0; gas.passed=0; gas.random=()=>.5;
gas.advance(.01); assert.equal(gas.clouds[0],cloud,'giant not recycled while inside');
assert(gas.transmission(0,0,2,0,0,1)<1,'behind-center giant still attenuates inside its radius');
cloud.z=-100; gas.advance(.01);
assert(gas.clouds[0].z-gas.clouds[0].radius*1.35>=184,'replacement starts beyond its entire far fade');
console.log('PASS giant lifecycle and attenuation');
// Colossal lifecycle: a radius-100 complex keeps working far beyond the old fixed planes.
const huge={x:0,y:0,z:-95,radius:100,stretch:1.2,shape:0,angle:0,color:0,texture:0,density:1};
gas.clouds=[huge]; gas.advance(.01);
assert(gas.clouds[0]===huge,'colossal survives well past the old -48 plane while the camera lies inside');
assert(gas.transmission(0,0,2,0,0,1)<1,'colossal behind center attenuates inside its radius');
gas.render({drawImage(){}},1280,720,0,0,0,1);
assert(gas.inside>0,'colossal immersion veil active behind its center');
huge.z=-200; gas.advance(.01);
assert(gas.clouds[0]!==huge,'colossal recycles only past its own radius-aware cutoff');
assert(gas.clouds[0].z-gas.clouds[0].radius*1.35>=184,'colossal replacement beyond its far fade');
console.log('PASS colossal lifecycle beyond old planes');
// Adjustable nebula field behind the new settings sliders.
gas.random=Math.random;
gas.count=48; gas.giantChance=0.065;
const field=Array.from({length:8000},()=>gas.make(100,0));
const share=field.filter(c=>c.radius>=12).length/field.length;
assert(share>0.05&&share<0.09,'default frequency ~6.5% giants or larger');
gas.giantChance=0;
assert.equal(Array.from({length:4000},()=>gas.make(100,0)).filter(c=>c.radius>=12).length,0,'0% slider removes both giant bands');
gas.giantChance=0.25;
const boosted=Array.from({length:4000},()=>gas.make(100,0)).filter(c=>c.radius>=12).length/4000;
assert(boosted>0.2&&boosted<0.3,'slider raises giant frequency proportionally');
gas.giantChance=0.065;
// Count slider keeps near clouds and spawns additions beyond the far fade.
const near=Array.from({length:48},(_,i)=>gas.make(i*2,i));
gas.clouds=near; gas.passed=0;
gas.setCount(12);
assert.equal(gas.clouds.length,12,'shrinking trims to requested count');
const kept=gas.clouds.map(c=>c.z).sort((a,b)=>a-b);
assert.deepEqual(kept,near.slice(0,12).map(c=>c.z).sort((a,b)=>a-b),'nearest clouds survive trimming');
gas.setCount(80);
assert.equal(gas.clouds.length,80,'growing reaches requested count');
for(const c of gas.clouds) if(!near.includes(c)) assert(c.z-c.radius*1.35>=184,'added clouds spawn beyond their far fade');
console.log('PASS cloud count and giant frequency sliders');
